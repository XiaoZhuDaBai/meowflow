/**
 * 模板/历史类型 → 现役类型的别名映射。
 * builtinTemplates.ts 中使用了早期类型命名（http.request / condition.if 等），
 * NODE_CATALOG 已切换为新版（tool.http / flow.condition 等）。
 * 在解析、配置面板、画布渲染等环节统一走别名映射，保证模板创建的节点可编辑。
 */
const NODE_TYPE_ALIASES: Record<string, string> = {
  // Tool
  'http.request': 'tool.http',
  // Control / Flow
  'condition.if': 'flow.condition',
  'condition.switch': 'flow.if-else',
  'flow.if-else': 'flow.if-else',
  // Transform / Code
  'code.transform': 'tool.code',
  // End / Aggregation
  'end.aggregator': 'flow.aggregation',
  'transform.aggregator': 'flow.aggregation',
};

export function findNodeDefinition(type: string): NodeDefinition | undefined {
  const direct = NODE_CATALOG.find((n) => n.type === type);
  if (direct) return direct;
  const alias = NODE_TYPE_ALIASES[type];
  if (alias) {
    return NODE_CATALOG.find((n) => n.type === alias);
  }
  return undefined;
}

/** 当前 type 是否存在别名映射（用于调试/日志） */
export function resolveNodeType(type: string): string {
  return NODE_TYPE_ALIASES[type] ?? type;
}
